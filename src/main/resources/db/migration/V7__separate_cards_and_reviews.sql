CREATE TABLE deck_cards (
    deck_id BIGINT NOT NULL,
    card_id BIGINT NOT NULL,
    CONSTRAINT pk_deck_cards PRIMARY KEY (deck_id, card_id),
    CONSTRAINT fk_deck_cards_deck FOREIGN KEY (deck_id) REFERENCES decks (id) ON DELETE CASCADE,
    CONSTRAINT fk_deck_cards_card FOREIGN KEY (card_id) REFERENCES cards (id) ON DELETE CASCADE
);

INSERT INTO deck_cards (deck_id, card_id)
SELECT deck_id, id
FROM cards
WHERE deck_id IS NOT NULL;

CREATE TABLE card_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    card_id BIGINT NOT NULL,
    repetitions INTEGER NOT NULL,
    interval INTEGER NOT NULL,
    easiness_factor DOUBLE PRECISION NOT NULL,
    last_review DATE,
    next_review DATE,
    CONSTRAINT uk_card_reviews_user_card UNIQUE (user_id, card_id),
    CONSTRAINT fk_card_reviews_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_card_reviews_card FOREIGN KEY (card_id) REFERENCES cards (id) ON DELETE CASCADE
);

INSERT INTO card_reviews (user_id, card_id, repetitions, interval, easiness_factor, last_review, next_review)
SELECT d.user_id, c.id, c.repetitions, c.interval, c.easiness_factor, c.last_review, c.next_review
FROM cards c
JOIN decks d ON d.id = c.deck_id
WHERE c.deck_id IS NOT NULL AND d.user_id IS NOT NULL;

