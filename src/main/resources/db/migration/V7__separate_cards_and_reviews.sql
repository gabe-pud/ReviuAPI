ALTER TABLE cards DROP COLUMN deck_id;
ALTER TABLE cards DROP COLUMN repetitions;
ALTER TABLE cards DROP COLUMN interval;
ALTER TABLE cards DROP COLUMN easiness_factor;
ALTER TABLE cards DROP COLUMN last_review;
ALTER TABLE cards DROP COLUMN next_review;

CREATE INDEX idx_deck_cards_card_id ON deck_cards (card_id);
CREATE INDEX idx_card_reviews_user_next_review ON card_reviews (user_id, next_review);
