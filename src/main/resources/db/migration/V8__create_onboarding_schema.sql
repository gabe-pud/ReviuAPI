CREATE TABLE user_onboarding (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE,
    foco_estudos VARCHAR(255) NOT NULL,
    prazo_final VARCHAR(255) NOT NULL,
    meta_diaria VARCHAR(255) NOT NULL,
    horario_foco VARCHAR(255) NOT NULL,
    retencao_conteudo VARCHAR(255) NOT NULL,
    ritmo_revisao VARCHAR(255) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_onboarding_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);